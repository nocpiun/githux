// Regenerates src/ui/repository_overview/language_colors.rs from a pinned GitHub Linguist
// lib/linguist/languages.yml. Kept in the repository so the compact offline table can be audited
// against its primary source instead of being hand-maintained.
//
// Usage (the upstream file is not vendored):
//   curl -sSLo /tmp/languages.yml \
//     https://raw.githubusercontent.com/github-linguist/linguist/<commit>/lib/linguist/languages.yml
//   node scripts/generate-linguist-language-colors.mjs /tmp/languages.yml \
//     src/ui/repository_overview/language_colors.rs <commit> <sha256-of-languages.yml>
//
// Only languages that declare a `color:` are emitted. Languages without a color, and names that
// are not in this table, use the documented neutral fallback in language_colors.rs.
import { readFileSync, writeFileSync } from 'node:fs';

const [source, target, commit, digest] = process.argv.slice(2);
if (!source || !target || !/^[a-f0-9]{40}$/.test(commit ?? '') || !/^[a-f0-9]{64}$/.test(digest ?? '')) {
  console.error(
    'Usage: node scripts/generate-linguist-language-colors.mjs <languages.yml> <output.rs> <40-hex commit> <64-hex sha256>'
  );
  process.exitCode = 1;
} else {
  const entries = new Map();
  let current = null;
  for (const line of readFileSync(source, 'utf8').split(/\r?\n/)) {
    const top = /^([^\s#][^:]*):\s*$/.exec(line);
    if (top) {
      current = top[1].trim();
      continue;
    }
    const color = /^\s{2}color:\s*"?#?([0-9a-fA-F]{6})"?\s*$/.exec(line);
    if (color && current) entries.set(current, color[1].toLowerCase());
  }
  // Byte-sorted so the runtime lookup can binary search without allocating.
  const names = [...entries.keys()].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  const rows = names
    .map((name) => `    ("${name}", 0x${entries.get(name)}),`)
    .join('\n');
  writeFileSync(
    target,
    `// Generated by scripts/generate-linguist-language-colors.mjs. Do not edit by hand.
//! GitHub Linguist colors for repository language strips.
//!
//! Source: https://github.com/github-linguist/linguist/blob/${commit}/lib/linguist/languages.yml
//! Pinned commit: \`${commit}\`
//! Source SHA-256: \`${digest}\`
//! Extracted: every top-level language that declares a \`color:\`. Languages without a color and
//! names that are missing here fall back to the neutral strip color, because inventing a hue would
//! misreport GitHub's own chart.
//!
//! GitHub Linguist is MIT licensed; the license text is retained in
//! \`assets/licenses/linguist-mit.txt\` and listed in \`THIRD_PARTY_NOTICES.md\`.
//!
//! Names are byte-sorted so lookups stay allocation-free.

use gpui::{Rgba, rgb};

/// GitHub Linguist's explicit color for a language name, if the pinned table has one.
pub(crate) fn linguist_color(name: &str) -> Option<Rgba> {
    LINGUIST_COLORS
        .binary_search_by(|(candidate, _)| candidate.cmp(&name))
        .ok()
        .map(|index| rgb(LINGUIST_COLORS[index].1))
}

static LINGUIST_COLORS: &[(&str, u32)] = &[
${rows}
];
`
  );
  console.log(`Wrote ${names.length} language colors to ${target}`);
}
